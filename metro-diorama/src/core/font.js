function compile(src) {
  const out = {};
  for (const [ch, rows] of Object.entries(src)) {
    const w = Math.max(...rows.map((r) => r.length));
    const pts = [];
    rows.forEach((r, y) => { for (let x = 0; x < r.length; x++) if (r[x] === '#') pts.push([x, y]); });
    out[ch] = { w, pts };
  }
  return out;
}

export const SMALL = { glyphs: compile(SMALL_SRC), h: 5, gap: 1, upper: true };
export const SIGN = { glyphs: compile(SIGN_SRC), h: 7, gap: 1, upper: false };

function glyphFor(font, ch) {
  const g = font.glyphs;
  if (font.upper) ch = ch.toUpperCase();
  return g[ch] || g[ch.toUpperCase()] || g[' '];
}

export function textWidth(font, str) {
  let w = 0;
  for (const ch of str) w += glyphFor(font, ch).w + font.gap;
  return Math.max(0, w - font.gap);
}

// plot(x, y) receives each ink pixel. Returns width.
export function drawText(font, str, x, y, plot) {
  let cx = x;
  for (const ch of str) {
    const g = glyphFor(font, ch);
    for (const [px, py] of g.pts) plot(cx + px, y + py);
    cx += g.w + font.gap;
  }
  return cx - x - font.gap;
}

export function textToPix(pix, font, str, x, y, color, a = 1) {
  return drawText(font, str, x, y, (px, py) => pix.set(px, py, color, a));
}

export function textToCtx(ctx, font, str, x, y, color) {
  ctx.fillStyle = color;
  return drawText(font, str, Math.round(x), Math.round(y), (px, py) => ctx.fillRect(px, py, 1, 1));
}
